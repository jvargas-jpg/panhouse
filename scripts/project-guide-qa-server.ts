/** Local, disposable QA: no workers, corporate Drive or outbound email. */
import 'dotenv/config';
import { Pool } from 'pg';
import { migrate } from 'drizzle-orm/node-postgres/migrator';
import { eq } from 'drizzle-orm';
const name=process.env.PANHOUSE_QA_DB??'panhouse_operation_preview';
if(!/^panhouse_(guide|operation)_preview(?:_[a-z0-9_]+)?$/.test(name)||name.length>63)throw Error('Invalid disposable QA database name');
const source=new URL(process.env.DATABASE_URL!);
if(!['localhost','127.0.0.1'].includes(source.hostname))throw Error('QA requires local PostgreSQL');
const admin=new Pool({connectionString:source.toString()});
if((await admin.query('SELECT 1 FROM pg_database WHERE datname=$1',[name])).rowCount)throw Error('QA database exists; it will not be overwritten.');
await admin.query(`CREATE DATABASE "${name}"`);await admin.end();
source.pathname='/'+name;process.env.DATABASE_URL=source.toString();process.env.NODE_ENV='development';
const {db}=await import('../server/db/client.js');
await migrate(db,{migrationsFolder:'./server/db/migrations'});
const schema=await import('../server/db/schema/index.js');
const {crearUsuario,crearProyectoDePrueba,completarPreparacionDePrueba}=await import('../tests/helpers/fixtures.js');
const {solicitarEditor}=await import('../server/helpers/proyectos.js');
const {createSession}=await import('../server/helpers/session.js');
const specialist=await crearUsuario('especialista'),chief=await crearUsuario('jefe_area'),editorChief=await crearUsuario('jefe_edicion');
await db.update(schema.users).set({nombre:'Elena · Especialista QA'}).where(eq(schema.users.id,specialist.id));
await db.update(schema.users).set({nombre:'Jefatura QA'}).where(eq(schema.users.id,chief.id));
const initial=await crearProyectoDePrueba({especialistaId:specialist.id,jefeAreaId:chief.id});
await db.update(schema.servicios).set({codigo:'EF',nombre:'Escritura Fantasma'}).where(eq(schema.servicios.id,initial.servicioId));
await db.update(schema.proyectos).set({titulo:'La casa de las palabras',notificadoJefatura:true}).where(eq(schema.proyectos.id,initial.id));
await db.update(schema.autores).set({nombre:'Elisa Vega'}).where(eq(schema.autores.id,initial.autorId));
await db.insert(schema.fichasTrazabilidad).values({proyectoId:initial.id});
await db.insert(schema.projectAssignments).values({proyectoId:initial.id,tipo:'especialista',usuarioId:specialist.id,asignadoPorId:chief.id});
const waiting=await crearProyectoDePrueba({especialistaId:specialist.id,jefeAreaId:chief.id});
await db.update(schema.proyectos).set({servicioId:initial.servicioId,titulo:'El oficio de recordar',notificadoJefatura:true}).where(eq(schema.proyectos.id,waiting.id));
await db.update(schema.autores).set({nombre:'Andrés Méndez'}).where(eq(schema.autores.id,waiting.autorId));
await db.insert(schema.fichasTrazabilidad).values({proyectoId:waiting.id});
await completarPreparacionDePrueba(waiting.id);await solicitarEditor(waiting.id,specialist.id);
const unassigned=await crearProyectoDePrueba({jefeAreaId:chief.id});
await db.update(schema.proyectos).set({servicioId:initial.servicioId,titulo:'Una historia por comenzar',notificadoJefatura:true}).where(eq(schema.proyectos.id,unassigned.id));
await db.insert(schema.fichasTrazabilidad).values({proyectoId:unassigned.id});
const {buildApp}=await import('../server/app.js');
const app=buildApp();
const roles={especialista:specialist.id,jefatura:chief.id,edicion:editorChief.id};
app.get<{Params:{role:string};Querystring:{project?:string}}>('/api/__qa/session/:role',async(req,reply)=>{
 const id=roles[req.params.role as keyof typeof roles];if(!id)return reply.code(404).send();
 const token=await createSession(id);
 const project=req.query.project==='waiting'?waiting.id:req.query.project==='initial'?initial.id:null;
 return reply.setCookie('panhouse_sid',token,{path:'/',httpOnly:true,sameSite:'lax'}).redirect(project?'/proyectos/'+project:'/');
});
app.get('/api/__qa/context',async()=>({initial:initial.id,waiting:waiting.id,unassigned:unassigned.id}));
await app.listen({host:'127.0.0.1',port:3017});
console.log('Project Guide QA ready on 3017; Vite 5177. Database: '+name+'. No external services.');
