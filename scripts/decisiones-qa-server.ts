import 'dotenv/config';
import { eq } from 'drizzle-orm';
import { migrate } from 'drizzle-orm/node-postgres/migrator';
import { writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
const source=new URL(process.env.DATABASE_URL!);
if(!['localhost','127.0.0.1'].includes(source.hostname)) throw new Error('Local QA only');
source.pathname='/panhouse_decisiones_qa';
process.env.DATABASE_URL=source.toString();process.env.NODE_ENV='development';
const {db}=await import('../server/db/client.js');
await migrate(db,{migrationsFolder:'./server/db/migrations'});
const {users,proyectos,fichasTrazabilidad,workItems,direccionesCreativas,disenos}=await import('../server/db/schema/index.js');
const {crearAutor,crearProyecto,crearFichaComercialCompleta}=await import('../tests/helpers/fixtures.js');
const {createSession}=await import('../server/helpers/session.js');
const [spec]=await db.select().from(users).where(eq(users.rol,'especialista'));
const [base]=await db.select().from(proyectos).limit(1);
const [soporte]=await db.select().from(users).where(eq(users.rol,'soporte_editorial'));
let [disenador]=await db.select().from(users).where(eq(users.rol,'disenador'));
if(!disenador) [disenador]=await db.insert(users).values({nombre:'Diseño QA',email:'decision-diseno-qa@panhouse.test',rol:'disenador',passwordHash:'session-only'}).returning();
let [p]=await db.select().from(proyectos).where(eq(proyectos.codigo,'DQ0005'));
if(!p) {
  const autor=await crearAutor({nombre:'Clara Silva'});
  p=await crearProyecto({autorId:autor.id,servicioId:base!.servicioId,unidadId:base!.unidadId,presupuestoId:base!.presupuestoId,especialistaId:spec!.id,disenadorId:disenador!.id,fechaProgramadaInicio:'2026-10-01',codigo:'DQ0005'});
  await db.update(proyectos).set({titulo:'Los mapas de la costa',estado:'en_proceso',notificadoJefatura:true}).where(eq(proyectos.id,p.id));
  await crearFichaComercialCompleta(p.id);
  const [cw]=await db.insert(workItems).values({proyectoId:p.id,tipo:'direccion_creativa',estado:'completado'}).returning();
  const [dc]=await db.insert(direccionesCreativas).values({proyectoId:p.id,workItemId:cw!.id,tipo:'concepto_portada',resultadoFinal:'aprobado'}).returning();
  const [dw]=await db.insert(workItems).values({proyectoId:p.id,tipo:'diseno',estado:'en_progreso'}).returning();
  const [d]=await db.insert(disenos).values({proyectoId:p.id,workItemId:dw!.id,tipo:'diagramacion',direccionCreativaId:dc!.id,fuenteUrl:'https://drive.google.com/tripa-qa',solicitudKey:crypto.randomUUID(),preparacionConfirmada:true}).returning();
  const {buildApp}=await import('../server/app.js');const app=buildApp();await app.ready();
  const diseñoCookie=`panhouse_sid=${await createSession(disenador!.id)}`;
  const entrega=await app.inject({method:'POST',url:`/api/diseno/${d!.id}/versiones`,headers:{cookie:diseñoCookie},payload:{enlace:'https://drive.google.com/version-qa',entregaKey:crypto.randomUUID()}});
  if(entrega.statusCode!==201) throw new Error(`QA handoff preparation failed: ${entrega.body}`);
  const handoff=await app.inject({method:'PATCH',url:`/api/diseno/${d!.id}/versiones/${entrega.json().id}`,headers:{cookie:`panhouse_sid=${await createSession(spec!.id)}`},payload:{accion:'handoff_calidad'}});
  if(handoff.statusCode!==200) throw new Error(`QA handoff failed: ${handoff.body}`);
  await app.close();
}
const token=await createSession(soporte!.id);
await writeFile(join(tmpdir(),'panhouse-browser-qa/state-decisiones-soporte.json'),JSON.stringify({cookies:[{name:'panhouse_sid',value:token,domain:'localhost',path:'/',expires:-1,httpOnly:true,secure:false,sameSite:'Lax'}],origins:[]}));
await writeFile(join(tmpdir(),'panhouse-browser-qa/case-decisiones-coleccion.json'),JSON.stringify({proyectoId:p.id}));
const {buildApp}=await import('../server/app.js');
await buildApp().listen({host:'127.0.0.1',port:3005});
